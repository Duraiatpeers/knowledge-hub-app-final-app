/**
 * features/auth/authSlice.ts
 *
 * Owns everything about "who is logged in".
 *
 * Before: `const [user, setUser] = useState<User | null>(null)` in App.tsx,
 *         with setUser passed down to <Login> and a logout callback passed
 *         down to <Header> (prop drilling).
 * After:  any component can read `state.auth.user` or dispatch `logout()`
 *         directly - no props needed.
 */
import { createAsyncThunk, createSlice } from '@reduxjs/toolkit'
import axios from 'axios'
import type { RootState } from '../../store/store'
import type { User } from '../../types'

const USERS_URL = 'http://localhost:3001/users'

/* ------------------------------------------------------------------ */
/* 1. State shape                                                      */
/* ------------------------------------------------------------------ */
interface AuthState {
  user: User | null
  // 'loading' while the login request is in flight - drives the button text
  status: 'idle' | 'loading' | 'failed'
  error: string | null
}

const initialState: AuthState = {
  user: null,
  status: 'idle',
  error: null,
}

/* ------------------------------------------------------------------ */
/* 2. Async thunk: loginUser                                           */
/* ------------------------------------------------------------------ */
/**
 * createAsyncThunk automatically dispatches three actions:
 *   auth/login/pending   -> before the request starts
 *   auth/login/fulfilled -> with the returned User
 *   auth/login/rejected  -> with the value passed to rejectWithValue()
 *
 * The component just calls: dispatch(loginUser({ username, password }))
 */
export const loginUser = createAsyncThunk<
  User,                                  // what we return on success
  { username: string; password: string }, // what the component passes in
  { rejectValue: string }                 // type of the error payload
>('auth/login', async ({ username, password }, { rejectWithValue }) => {
  try {
    const response = await axios.get<User[]>(USERS_URL, { params: { username } })
    const matchedUser = response.data[0]

    // Mock auth: compare the plain-text password from db.json.
    if (matchedUser && matchedUser.password === password) {
      return matchedUser
    }
    return rejectWithValue('Incorrect username or password.')
  } catch (err) {
    console.error('Login request failed:', err)
    return rejectWithValue('Could not reach the server. Is json-server running?')
  }
})

/* ------------------------------------------------------------------ */
/* 3. The slice: reducers + extraReducers                              */
/* ------------------------------------------------------------------ */
const authSlice = createSlice({
  name: 'auth',
  initialState,

  // Synchronous actions -> auto-generated action creators (authSlice.actions)
  reducers: {
    // dispatch(logout())  - replaces App's handleLogout / setUser(null)
    logout(state) {
      state.user = null
      state.status = 'idle'
      state.error = null
    },
  },

  // React to the actions generated by the loginUser thunk
  extraReducers: builder => {
    builder
      .addCase(loginUser.pending, state => {
        state.status = 'loading'
        state.error = null
      })
      .addCase(loginUser.fulfilled, (state, action) => {
        // Immer lets us "mutate" - it produces a new immutable state under the hood
        state.user = action.payload
        state.status = 'idle'
      })
      .addCase(loginUser.rejected, (state, action) => {
        state.status = 'failed'
        state.error = action.payload ?? 'Login failed.'
      })
  },
})

export const { logout } = authSlice.actions
export default authSlice.reducer

/* ------------------------------------------------------------------ */
/* 4. Selectors - the ONLY way components should read auth state      */
/* ------------------------------------------------------------------ */
export const selectCurrentUser = (state: RootState) => state.auth.user
export const selectIsLoggedIn = (state: RootState) => state.auth.user !== null
export const selectAuthStatus = (state: RootState) => state.auth.status
export const selectAuthError = (state: RootState) => state.auth.error
